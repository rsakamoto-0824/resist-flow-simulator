function config = defaultConfig(mode)
%DEFAULTCONFIG Return demonstrative parameters; lengths are in micrometers.
if nargin < 1
    mode = 'leveling';
end
mode = validatestring(mode, {'leveling', 'spin', 'infiltration'});
config = struct( ...
    'mode', mode, 'n', 16, 'lengthUm', 80, 'thicknessUm', 1, ...
    'amplitudeUm', 0.2, 'pattern', 'sine', 'substrateUm', 0, ...
    'substratePattern', 'flat', 'viscosityPaS', 0.1, ...
    'surfaceTensionMnM', 30, 'densityKgM3', 1000, 'rpm', 3000, ...
    'evaporationNmS', 0, 'solidsFraction', 0.2, ...
    'concentrationFactor', 8, 'temperatureC', 25, ...
    'activationKJMol', 0, 'durationS', 1, 'accuracy', 1, ...
    'gapUm', 0.2, 'depthUm', 5, 'contactAngleDeg', 45, ...
    'externalPressurePa', 0);
if strcmp(mode, 'spin')
    config.thicknessUm = 5;
    config.durationS = 10;
elseif strcmp(mode, 'infiltration')
    config.viscosityPaS = 0.001;
    config.surfaceTensionMnM = 72;
    config.durationS = 0.001;
end
end
